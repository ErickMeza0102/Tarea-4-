import tensorflow as tf
from tensorflow import keras
from tensorflow.keras import layers
from tensorflow.keras.preprocessing.image import ImageDataGenerator

# ==========================================
# PASO 1: Entrenar red convolucional con CelebA
# ==========================================
# NOTA: Para este ejemplo, crearemos una red desde cero.
# En un caso real, cargarías el dataset CelebA y entrenarías esta red para predecir los 40 atributos.

def crear_modelo_base():
    model = keras.models.Sequential([
        # Capa convolucional inicial
        layers.Conv2D(32, (3, 3), activation='relu', input_shape=(224, 224, 3)),
        layers.MaxPooling2D((2, 2)),
        layers.Conv2D(64, (3, 3), activation='relu'),
        layers.MaxPooling2D((2, 2)),
        layers.Conv2D(128, (3, 3), activation='relu'),
        layers.MaxPooling2D((2, 2)),
        # Clasificador para los 40 atributos de CelebA
        layers.Flatten(),
        layers.Dense(128, activation='relu'),
        layers.Dense(40, activation='sigmoid') # 40 atributos
    ])
    model.compile(optimizer='adam', loss='binary_crossentropy', metrics=['accuracy'])
    return model

print("--- PASO 1: Creando y entrenando modelo base (Simulado) ---")
modelo_base = crear_modelo_base()
# modelo_base.fit(datos_celebA_X, datos_celebA_Y, epochs=10) # Se comenta para que el código corra sin datos reales
print("Modelo base creado con éxito.")

# ==========================================
# PASO 2 y 3: Construir nuevo modelo y añadir clasificador
# ==========================================
print("\n--- PASO 2 y 3: Construyendo modelo de reconocimiento facial ---")

# Creamos un nuevo modelo secuencial
modelo_facial = keras.models.Sequential()

# PASO 2: Agregar capas convolucionales del modelo entrenado (quitando el clasificador denso)
# Iteramos sobre las capas del modelo base, pero nos detenemos antes de las capas densas (Flatten, Dense)
for layer in modelo_base.layers:
    if not isinstance(layer, layers.Dense) and not isinstance(layer, layers.Flatten):
        modelo_facial.add(layer)

# PASO 3: Aumentar un clasificador apropiado (una sola neurona de salida)
modelo_facial.add(layers.Flatten())
# El texto sugiere una o dos capas densas antes de la salida
modelo_facial.add(layers.Dense(64, activation='relu'))
# Capa de salida: 1 neurona (es mi rostro o no) con activación sigmoide
modelo_facial.add(layers.Dense(1, activation='sigmoid'))

modelo_facial.summary()

# ==========================================
# PASO 4: Congelar los pesos de la parte pre-entrenada
# ==========================================
print("\n--- PASO 4: Congelando capas convolucionales ---")

# Según la sección 3.2, congelamos las capas iniciales.
# Asumiendo que las capas convolucionales son las primeras 6 capas de nuestro modelo_facial
for layer in modelo_facial.layers[:6]:
    layer.trainable = False
    print(f"Capa {layer.name} congelada (trainable=False)")

# ==========================================
# PASO 5: Entrenar este modelo
# ==========================================
print("\n--- PASO 5: Compilando y preparando para entrenar ---")

modelo_facial.compile(
    optimizer='adam',
    loss='binary_crossentropy',
    metrics=['accuracy']
)

